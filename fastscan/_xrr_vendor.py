def report_families(cand):
    """Given a basin candidate dict (from run_pipeline), package both homometric families:
      - 'nyquist_total': full resolution-limited family size at dz=pi/q_max (densifying)
      - 'intrinsic': the sparsest members (physical profile + mirror) = grid-independent core
      - 'nif_hist': {interface_count: n_members} spread linking the two
    The Nyquist grid is the principled cutoff: features finer than dz=pi/q_max sit above q_max
    and cannot be confirmed by the data, so densification is capped here."""
    from collections import Counter
    mem=cand['family']
    nif=[int(np.sum(np.abs(gg)>1e-3)) for gg in mem]
    nmin=min(nif)
    return dict(nyquist_total=len(mem),
                intrinsic=sum(k==nmin for k in nif),      # sparsest = profile+mirror
                min_interfaces=nmin,
                nif_hist=dict(sorted(Counter(nif).items())),
                m=cand['m'])

def on_boundary(th,N,L0,rt,rb,rtol=0.01,min_gap_A=1.3):
    """A candidate is rejected only if it shows a true pathology: the span pinned at an extreme
    bound, the roughness pinned high, an unphysical (near-negative) density, or a collapsed interior
    box. A density sitting at the upper (physical) ceiling is NOT rejected -- that is a soft
    direction, reported as a band by the caller."""
    zpos,rbx,sg,span=NB._unpack_sb(th,N)
    flags=[]; spanrng=(SPAN_HI-SPAN_LO)*L0
    if min(abs(span-SPAN_LO*L0),abs(span-SPAN_HI*L0)) < rtol*spanrng: flags.append('span')
    if abs(sg-8.0) < 0.06: flags.append('sigma_high')
    if np.min(rbx) < (rt-0.15)+0.02: flags.append('rho_unphysical')
    if N>1 and np.min(np.diff(zpos)) < min_gap_A: flags.append('coincident')
    return bool(flags), flags



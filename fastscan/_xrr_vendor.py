# ============================================================================
# Patterson peak heights -> slab contrasts  (N-box generalization of Appendix A)
# ============================================================================
#
# The writeup Appendix A treats the clean 2-box (3 interfaces): with steps
# d0,d1,d2 summing to the contrast K, the origin peak is G(0)=d0^2+d1^2+d2^2 and
# the outermost peak is the single end-to-end pair G(z3)=d0*d2, so the scale-free
# ratio R=G(z3)/G(0) fixes the contrasts up to the mirror (the +/- discriminant).
#
# The general statement is one line of the polynomial picture: sampled on the
# Nyquist grid the interface steps form a vector g (sum g = K), and the Patterson
# peak heights ARE the autocorrelation of g,
#
#     G[k] = a_k = sum_j g_j * g_{j+k},      G[0] = sum_j g_j^2,   G[M] = g_0 g_M,
#
# i.e. the height at a lag ell is the sum of step PRODUCTS over every interface
# pair separated by ell. Two facts carry straight over from the 2-box:
#   (i) the OUTERMOST resolved lag is always a single pair -> G(span) = d_0 d_N;
#   (ii) recovering the steps from {G(ell)} is the phase problem, so it is
#        non-unique: it is exactly spectral factorization (`spectral_members`),
#        giving up to 2^m homometric branches, the whole-sequence reversal (mirror)
#        always among them.
#
# Degeneracy accounting (the generalization of "fix d1, solve the outer pair"):
# with the interface POSITIONS taken from turnpike, the scale-free data give one
# contrast constraint (sum d = K) plus one product equation per RESOLVED lag. The
# continuous nullity -- the number of interior contrasts the data leave free --
# is (#steps) - (#independent equations); each such direction is an under-resolved
# interior interface (a Fisher soft direction / flat-basin dimension). The discrete
# branches on top of that are the 2^m zero-flips. For the 2-box lipid only the
# outermost lag is resolved (the ~6 A interior sits below 2pi/qmax), leaving exactly
# one continuous freedom (the head/tail split d1) and the +/- mirror -- precisely
# the two data-degenerate candidates the pipeline finds.
#
# Caveat carried over and made quantitative below: if an END contrast is weak
# (d_0 or d_N ~ 0) the outermost product G(span)=d_0 d_N is faint and the Patterson
# span is under-read -- the ErLD case, where d_0 d_N ~ 2e-4 << G(0).


def contrast_ratio_outer(g):
    """Scale-free outer ratio R = G(span)/G(0) = g_0 g_M / sum g^2 for a grid step
    vector g (the N-box generalization of Eq. (12)'s left-hand side)."""
    g = np.asarray(g, float)
    return float(g[0] * g[-1] / np.sum(g ** 2))


def solve_2box_closed(R, K, d1):
    """Base case (writeup Appendix A). Three interfaces, steps d0,d1,d2, sum=K,
    ratio R=d0 d2/(d0^2+d1^2+d2^2). Fixing the interior step d1 (the under-resolved
    direction) returns the mirror pair (d0,d2) and (d2,d0), or None if the
    discriminant is negative (no real slab assignment -> candidate rejected)."""
    S = K - d1                       # = d0 + d2
    Q = R * (S ** 2 + d1 ** 2) / (1.0 + 2.0 * R)   # = d0 d2
    disc = S ** 2 - 4.0 * Q
    if disc < 0:
        return None
    root = math.sqrt(disc)
    d0a, d2a = 0.5 * (S + root), 0.5 * (S - root)
    return ((float(d0a), float(d1), float(d2a)),
            (float(d2a), float(d1), float(d0a)))     # the two orderings = mirror pair


def contrasts_from_patterson(g_or_a, K, is_autocorr=False, sig_tol=0.04):
    """General N-box inverse: recover the homometric set of grid step vectors that
    reproduce the given Patterson (= autocorrelation) and total contrast K.

    g_or_a : either a grid step vector g (is_autocorr=False) or its autocorrelation
             coefficients a_0..a_M (is_autocorr=True, i.e. the resolved peak heights).
    Returns (members, m, info) where members is the list of step vectors sharing |F|^2
    exactly, m the number of flippable (off-unit-circle) zero pairs, and info records
    G(0), the outer product, and the outer ratio. This is the same spectral
    factorization used in Stage C2; presented here as 'contrasts from the Patterson'."""
    if is_autocorr:
        a = np.asarray(g_or_a, float)
    else:
        a = autocorr_exact(np.asarray(g_or_a, float))
    members, m = spectral_members(a, K, sig_tol=sig_tol)
    info = dict(G0=float(a[0]), outer_product=float(a[-1]),
                outer_ratio=float(a[-1] / a[0]) if a[0] else float('nan'))
    return members, m, info


def contrast_nullity(n_steps, n_resolved_lags, signed=False):
    """Continuous degeneracy in the CONTRAST assignment given the turnpike positions:
    (#steps) - (#independent scale-free equations), the equations being the contrast
    constraint plus one product per resolved lag. Each unit is an under-resolved
    interior interface (a Fisher soft direction). 2-box lipid: n_steps=3, one resolved
    lag -> 3-(1+1)=1 (the head/tail split).

    NOTE this is a generic dimension count, not a rank: the product equations are
    quadratic, so at special configurations (near-palindromic step vectors, coincident
    positions) the true nullity can exceed it. Cross-check against the FIM soft count,
    which is now units-invariant. Returns max(.,0); use `signed=True` to see the
    over-determined case, which signals an inconsistent position set or peak list."""
    n = n_steps - (n_resolved_lags + 1)
    return n if signed else max(n, 0)


def _contrast_selftest():
    """Verify the identities on the Liang PNAS reference profiles and the 2-box base case."""
    print("=" * 72)
    print("Patterson-contrast self-test (N-box generalization of Appendix A)")
    print("=" * 72)

    def steps(rt, rb, box_rho):
        rho = [rt] + list(box_rho) + [rb]
        return np.diff(rho)

    cases = {
        'ErLD (3-box)': dict(rt=0.2574, rb=0.333, box_rho=[0.279, 0.33, 0.324],
                             thick=[18.9, 9, 18]),
        'Y (4-box)':    dict(rt=0.2574, rb=0.333, box_rho=[0.303, 0.42, 0.332, 0.265],
                             thick=[21.5, 6, 16, 9]),
    }
    for name, c in cases.items():
        d = steps(c['rt'], c['rb'], c['box_rho'])
        K = c['rb'] - c['rt']
        z = np.concatenate([[0.0], np.cumsum(c['thick'])])
        # exact forward identities (arbitrary positions, not gridded)
        G0 = np.sum(d ** 2)
        Gspan = d[0] * d[-1]
        print(f"\n{name}: steps d={np.round(d,4)}  sum d={d.sum():.4f} (K={K:.4f})")
        print(f"  G(0)=sum d^2          = {G0:.3e}")
        print(f"  G(span)=d0*dN         = {Gspan:.3e}   (outer ratio R={Gspan/G0:.3e})")
        print(f"  span z_N              = {z[-1]:.1f} A;  end contrasts d0={d[0]:.4f}, dN={d[-1]:.4f}")
        if abs(d[0]) < 0.03 or abs(d[-1]) < 0.03:
            print(f"  -> weak end contrast: outermost Patterson peak is faint (span under-read).")

    # base case: a clean synthetic 2-box, recover the mirror pair in closed form
    print("\nBase case (2-box closed form): d=[0.10, -0.06, 0.293], K=0.333")
    d = np.array([0.10, -0.06, 0.293]); K = d.sum()
    R = d[0] * d[2] / np.sum(d ** 2)
    sol = solve_2box_closed(R, K, d[1])
    fmt = lambda t: "(" + ", ".join(f"{x:.4f}" for x in t) + ")"
    print(f"  R={R:.4f}; solve_2box_closed(R,K,d1) -> {fmt(sol[0])} and {fmt(sol[1])}")
    ok = np.allclose(sorted(sol[0]), sorted([d[0], d[1], d[2]]), atol=1e-6)
    print(f"  recovers input triple (up to ordering/mirror): {ok}")

    # general inverse via spectral factorization on a gridded 2-box
    print("\nGeneral inverse (spectral factorization) on a gridded sparse 2-box:")
    g = np.zeros(8); g[0] = 0.10; g[3] = -0.06; g[7] = 0.293
    mem, m, info = contrasts_from_patterson(g, g.sum())
    core = [gg for gg in mem if int(np.sum(np.abs(gg) > 1e-3)) == 3]
    print(f"  m(flip units)={m}, total members={len(mem)} (2^m={2**m}), "
          f"intrinsic 3-interface core={len(core)} (profile+mirror)")
    print(f"  G(0)={info['G0']:.3e}, outer product={info['outer_product']:.3e}")

    # degeneracy accounting
    print("\nContrast nullity (given turnpike positions):")
    print(f"  2-box, 1 resolved lag (interior blended): nullity="
          f"{contrast_nullity(3,1)}  (the head/tail split) + mirror branch")
    print(f"  3-box, 2 resolved lags:                   nullity={contrast_nullity(4,2)}")
    print("=" * 72)



def autocorr_exact(g):
    M=len(g)-1; return np.array([np.sum(g[:len(g)-k]*g[k:]) for k in range(M+1)])

def _cluster(vals, tol):
    """Cluster complex values; return list of (representative, multiplicity, [indices])."""
    out = []
    for i, v in enumerate(vals):
        for c in out:
            if abs(v - c[0]) <= tol:
                c[1] += 1; c[2].append(i)
                c[0] = (c[0] * (c[1] - 1) + v) / c[1]      # running mean
                break
        else:
            out.append([v, 1, [i]])
    return out


def _spectral_members_at(a, contrast, sig_tol=0.04, circ_tol=1e-5,
                         allow_zero_contrast=False):
    """Enumerate the exact homometric family (Axis 1) of a step vector from its
    autocorrelation coefficients a_0..a_M.

    Roots of the palindromic autocorrelation polynomial come as reciprocal pairs
    {r, 1/r}; for real coefficients they must be flipped in CONJUGATION-CLOSED
    units, i.e. a real root singly but a complex root together with its conjugate.
    Each unit carries exactly one binary flip, so |family| = 2^m with m = #units
    (before de-duplication, which only collapses self-mirror-symmetric profiles).

    Roots on the unit circle carry no flip freedom; they occur with even
    multiplicity and exactly half go into every factor.

    Returns (members, m), or (members, m, info) if return_info.
    """
    a = np.asarray(a, float)
    M = len(a) - 1
    scale = np.sqrt(max(a[0], 0.0))
    info = dict(n_units=0, n_oncircle=0, warnings=[])

    if abs(contrast) < 1e-12 * max(scale, 1e-12) and not allow_zero_contrast:
        raise ValueError(
            "spectral_members: net contrast is zero (sum g = 0), so the global sign "
            "of each factor is undetermined and the family cannot be oriented. This "
            "is the symmetric-bilayer-in-water case. Either enumerate a NET-CONTRAST "
            "sub-stack (e.g. include the substrate step), or pass "
            "allow_zero_contrast=True to accept a first-nonzero-positive sign convention.")

    if M == 0:
        g = np.array([contrast if contrast else scale])
        return (([g], 0, info) if return_info else ([g], 0))

    P = np.concatenate([a[:0:-1], a])          # palindromic, ascending powers
    roots = np.roots(P[::-1])

    inside  = [r for r in roots if abs(r) < 1.0 - circ_tol]
    outside = [r for r in roots if abs(r) > 1.0 + circ_tol]
    oncirc  = [r for r in roots if abs(abs(r) - 1.0) <= circ_tol]
    amb = [r for r in roots if circ_tol < abs(abs(r) - 1.0) < 1e-3]
    if amb:
        info['warnings'].append(
            f"{len(amb)} root(s) within 1e-3 of the unit circle but outside circ_tol="
            f"{circ_tol:g}: the flip they carry is numerically marginal, so the family "
            "size here is conditioning-limited, not a structural fact")
    if len(inside) != len(outside):
        info['warnings'].append(
            f"inside/outside root counts differ ({len(inside)} vs {len(outside)}); "
            "roots are near the unit circle -- family may be incomplete")

    # --- conjugation-closed flip units from the inside roots ---
    imtol = 1e-6 * max(1.0, max((abs(r) for r in inside), default=1.0))
    used = [False] * len(inside)
    units = []
    for i, r in enumerate(inside):
        if used[i]:
            continue
        if abs(r.imag) <= imtol:
            used[i] = True
            units.append([complex(r.real, 0.0)])
        else:
            j, bd = None, np.inf
            for k in range(len(inside)):
                if k == i or used[k]:
                    continue
                d = abs(inside[k] - np.conj(r))
                if d < bd:
                    bd, j = d, k
            if j is None:
                used[i] = True
                units.append([complex(r.real, 0.0)])
                info['warnings'].append("unpaired complex root; conjugate partner missing")
            else:
                used[i] = used[j] = True
                units.append([r, inside[j]])

    # --- on-circle roots: take half of each cluster's multiplicity ---
    base = []
    for rep, mult, _ in _cluster(oncirc, 10 * circ_tol):
        if mult % 2:
            info['warnings'].append(
                f"on-circle root {rep:.4g} has odd multiplicity {mult}; "
                "taking floor(mult/2) -- autocorrelation may be ill-conditioned")
        base += [rep] * (mult // 2)

    m = len(units)
    info['n_units'] = m
    info['n_oncircle'] = len(oncirc)

    members = []
    for nf in range(m + 1):
        for sub in combinations(range(m), nf):
            chosen = list(base)
            for k, u in enumerate(units):
                chosen += [1.0 / x for x in u] if k in sub else list(u)
            if len(chosen) != M:
                info['warnings'].append(
                    f"factor has degree {len(chosen)}, expected {M}: multiple/ill-conditioned "
                    "roots lost -- member skipped")
                continue
            poly = np.poly(chosen) if chosen else np.array([1.0])
            if np.max(np.abs(poly.imag)) > 1e-6 * max(np.max(np.abs(poly.real)), 1e-12):
                info['warnings'].append("non-real factor produced -- root grouping failed")
                continue
            cf = poly[::-1].real
            s = np.sqrt(a[0] / max(np.sum(cf ** 2), 1e-300))
            cf = cf * s
            if abs(cf.sum() - contrast) > abs(cf.sum() + contrast):
                cf = -cf
            if allow_zero_contrast and abs(contrast) < 1e-12 * max(scale, 1e-12):
                nz = np.flatnonzero(np.abs(cf) > 1e-12 * scale)
                if len(nz) and cf[nz[0]] < 0:
                    cf = -cf
            members.append(cf)

    # --- de-duplicate with a tolerance SCALED to the profile magnitude ---
    dtol = max(1e-4 * scale, 1e-12)
    uniq = []
    for g in members:
        if not any(len(u) == len(g) and np.max(np.abs(u - g)) <= dtol for u in uniq):
            uniq.append(g)
    info['n_before_dedupe'] = len(members)
    info['n_after_dedupe'] = len(uniq)
    info['n_skipped'] = 2 ** m - len(members)
    info['circ_tol'] = circ_tol
    return uniq, m, info


def spectral_members(a, contrast, sig_tol=0.04, circ_tol=1e-5,
                     allow_zero_contrast=False, return_info=False):
    """Exact homometric family (Axis 1) from autocorrelation coefficients a_0..a_M.

    Wraps the core factorization in a progressive relaxation of `circ_tol`. A root of
    high multiplicity on the unit circle is scattered by np.roots by ~eps**(1/mult),
    so a tolerance tight enough to preserve a genuine near-circle flip is too tight to
    recognise a clustered multiple root; when that costs members (detected by the
    factor-degree check) the band is widened until the cluster is captured whole.

    Returns (members, m) or (members, m, info). `m` is the number of independent
    conjugation-closed zero-flip units, so |family| = 2^m before de-duplication --
    check info['family_complete'] before relying on that identity.
    """
    best = None
    for ct in (circ_tol, 1e-4, 1e-3, 1e-2):
        if ct < circ_tol:
            continue
        try:
            uniq, m, info = _spectral_members_at(a, contrast, sig_tol, ct, allow_zero_contrast)
        except ValueError:
            raise
        if best is None or info['n_skipped'] < best[2]['n_skipped'] \
                or (info['n_skipped'] == best[2]['n_skipped'] and len(uniq) > len(best[0])):
            best = (uniq, m, info)
        if info['n_skipped'] == 0 and uniq:
            break
    uniq, m, info = best
    if info['circ_tol'] != circ_tol:
        info['warnings'].append(
            f"circ_tol relaxed {circ_tol:g} -> {info['circ_tol']:g} to recover complete "
            "factors from a clustered/multiple root")
    info['family_complete'] = (info['n_skipped'] == 0)
    if not info['family_complete']:
        info['warnings'].append(
            f"{info['n_skipped']} factor(s) unrecoverable; |family| = 2^m does NOT hold here")
    return ((uniq, m, info) if return_info else (uniq, m))



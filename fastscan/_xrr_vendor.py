def scan_basin(q,r,e,N,L,dz,rt,rb,kind='kin',nfev=300,fit_yscale=True,fit_qoff=True):
    nodes=np.arange(dz,L-1e-6,dz)/L
    if len(nodes)<N-1: nodes=np.linspace(0.15,0.85,max(N-1,3))
    dens=[[0.31]*N,[0.45]+[0.31]*(N-1),[0.15]+[0.31]*(N-1),
          [rt+0.06]+[0.47]*(N-1),                         # low-first / high-rest (dense-head split)
          list(np.linspace(rt+0.04,0.44,N))]              # rising
    combos=list(combinations(nodes,N-1)) if N>1 else [()]
    cands=[]
    for ps in combos:
        for dp in dens:
            seed=np.concatenate([[L],np.array(ps),np.array(dp[:N]),[3.3]])
            try:
                th,ssr,ys,qoff=NB.refine_spanbounded(q,r,e,seed,N,L,rt,rb,kind=kind,nfev=nfev,
                                                     span_lo=SPAN_LO,span_hi=SPAN_HI,rho_hi=RHO_HI,
                                                     fit_yscale=fit_yscale,fit_qoff=fit_qoff)
            except Exception:
                continue
            if not np.isfinite(ssr): continue
            cands.append((ssr/len(q),th,ys,qoff))
    cands.sort(key=lambda x:x[0])
    uniq=[]
    for chi,th,ys,qoff in cands:
        zpos,rbx,sg,span=NB._unpack_sb(th,N)
        sig=(tuple(np.round(np.sort(zpos[1:-1]),0)),tuple(np.round(np.sort(rbx),2)))
        if not any(sig==u[-1] for u in uniq): uniq.append((chi,th,ys,qoff,sig))
    return [(c,t,y,qo) for c,t,y,qo,_ in uniq]

def fim_full(q,e,th,N,rt,rb,kind='kin',hrel=0.01,scaled=True):
    """Fisher information F = J^T J (error-weighted), by CENTRAL differences.

    Eigenvalues of J^T J in raw parameter space are units-dependent -- span is in
    angstrom, densities in e/A^3, sigma in angstrom -- so a soft-direction count
    thresholded on lam < 1e-2 lam_max changes if a parameter is merely re-expressed
    in different units. With scaled=True the Jacobian columns are multiplied by the
    parameter scales s_k = max(|th_k|, floor), i.e. the information is computed for
    the DIMENSIONLESS fractional parameters d ln th_k, making the spectrum and the
    soft count invariant to unit choice.

    Returns (eigenvalues descending, eigenvectors as columns descending). The
    eigenvectors are returned as RAW parameter-space displacements (v_raw = S v),
    unnormalised, so that th + sqrt(chi/lam_k) * V[:,k] remains the correct
    1-sigma excursion used by the band builder.
    """
    def model(t):
        zpos,rbx,sg,_=NB._unpack_sb(t,N)
        if kind=='kin': return NB.kin_RoRF(q,zpos,NB._steps(rbx,rt,rb),sg,rb-rt)
        return NB.parratt_RoRF(q,np.diff(zpos),rbx,sg,rt,rb)
    P=len(th); J=np.zeros((len(q),P))
    h=np.array([max(hrel*abs(th[k]),1e-3) for k in range(P)])
    for k in range(P):
        tp=th.copy(); tp[k]+=h[k]
        tm=th.copy(); tm[k]-=h[k]
        J[:,k]=(model(tp)-model(tm))/(2.0*h[k])/e
    S=np.ones(P)
    if scaled:
        S=np.array([max(abs(th[k]),1e-3) for k in range(P)])
        J=J*S[None,:]
    w,V=np.linalg.eigh(J.T@J)            # ascending
    w=np.maximum(w[::-1],1e-12); V=V[:,::-1]
    return w, (S[:,None]*V if scaled else V)

def fim_spectrum(q,e,th,N,rt,rb,kind='kin'):
    w,_=fim_full(q,e,th,N,rt,rb,kind); return w

def homometric_family(th,N,dz,rt,rb):
    zpos,rbx,sg,span=NB._unpack_sb(th,N); steps=NB._steps(rbx,rt,rb)
    zg=np.round(zpos/dz).astype(int); g=np.zeros(zg.max()+1)
    for n,s in zip(zg,steps): g[n]+=s
    mem,m=spectral_members(autocorr_exact(g), g.sum())
    return mem,g,sg,m

def nearest_member(mem,g):
    """Representative of the homometric family: the member CLOSEST to the fitted g.

    Renamed from `most_physical`, which overclaimed -- it applies no physicality test
    (no density bounds, no minimum layer thickness), and since the fitted g is always
    itself a member it trivially returns g. Use `physical_members` to actually filter.
    Returns None for an empty family rather than raising."""
    if not len(mem): return None
    return min(mem,key=lambda gg: np.sum((gg-g)**2) if len(gg)==len(g) else 1e9)

most_physical = nearest_member        # backward-compatible alias

def physical_members(mem,rt,dz,rho_lo=-0.02,rho_hi=0.60,min_thick=None):
    """Filter a homometric family to members whose cumulative profile stays inside a
    physically plausible density window, and (if min_thick given) whose non-zero steps
    are separated by at least that thickness. This is the test `most_physical` never did."""
    out=[]
    for g in mem:
        rho=rt+np.cumsum(g)
        if np.any(rho<rho_lo) or np.any(rho>rho_hi): continue
        if min_thick is not None:
            nz=np.flatnonzero(np.abs(g)>1e-3*max(np.max(np.abs(g)),1e-12))
            if len(nz)>1 and np.min(np.diff(nz))*dz < min_thick: continue
        out.append(g)
    return out

def _yscale(R,r,e): return float(np.sum(R*r/e**2)/np.sum(R**2/e**2))

def parratt_grid(q,r,e,g,dz,sg,rt,rb,qoff=0.0):
    z=np.arange(len(g))*dz; rp=NB.parratt_RoRF(q+qoff,np.diff(z),rt+np.cumsum(g)[:-1],sg,rt,rb)
    return np.sum(((_yscale(rp,r,e)*rp-r)/e)**2)/len(q)

def kin_grid(q,r,e,g,dz,sg,rt,rb,qoff=0.0):
    z=np.arange(len(g))*dz; rk=NB.kin_RoRF(q+qoff,z,g,sg,rb-rt)
    return np.sum(((_yscale(rk,r,e)*rk-r)/e)**2)/len(q)

def run_pipeline(path,contrast,rt,rb,N,name='',verbose=True,fit_yscale=True,fit_qoff=True):
    pat=resolve_patterson(path); q,r,e=pat['q'],pat['r'],pat['e']; L=pat['span']; dz=pat['dz']
    basin0=scan_basin(q,r,e,N,L,dz,rt,rb,kind='kin',fit_yscale=fit_yscale,fit_qoff=fit_qoff)
    basin=[]                                                  # Parratt-polish each distinct candidate
    for _,th0,_,_ in basin0[:8]:
        try:
            thp,ssrp,ys,qoff=NB.refine_spanbounded(q,r,e,th0,N,L,rt,rb,kind='parratt',nfev=250,
                                                   span_lo=SPAN_LO,span_hi=SPAN_HI,rho_hi=RHO_HI,
                                                   fit_yscale=fit_yscale,fit_qoff=fit_qoff)
        except Exception:
            continue
        if not np.isfinite(ssrp): continue
        basin.append((ssrp/len(q),thp,ys,qoff))
    basin.sort(key=lambda x:x[0])
    basin=[c for c in basin if not on_boundary(c[1],N,L,rt,rb)[0]]   # drop genuine runaways only
    if basin:                                                        # drop junk far above the best fit
        cmin=min(c[0] for c in basin); basin=[c for c in basin if c[0] < 3.0*cmin]
    out=dict(name=name,N=N,rt=rt,rb=rb,pat=pat,L=L,dz=dz,q=q,r=r,e=e,basin=[])
    if verbose:
        print(f"\n=== {name} ({N}-box) === Patterson peaks z={np.round(pat['zpk'],1)} "
              f"-> span={L:.1f}A, resolution={pat['res']:.1f}A, Nyquist dz={dz:.1f}A; basin candidates={len(basin)}")
    for ci,(chi,th,ys,qoff) in enumerate(basin):
        zpos,rbx,sg,span=NB._unpack_sb(th,N)
        ev=fim_spectrum(q,e,th,N,rt,rb,kind='kin'); soft=int(np.sum(ev<1e-2*ev[0]))
        try:
            mem,g,sgg,m=homometric_family(th,N,dz,rt,rb)
        except ValueError as ex:                       # zero net contrast -> family undefined
            print(f"  cand {ci+1}: homometric family skipped ({ex.args[0].splitlines()[0]})")
            mem,g,sgg,m=[],None,sg,0
        rep=nearest_member(mem,g) if len(mem) else None
        kin=np.array([kin_grid(q,r,e,gg,dz,sgg,rt,rb,qoff) for gg in mem])
        par=np.array([parratt_grid(q,r,e,gg,dz,sgg,rt,rb,qoff) for gg in mem])
        out['basin'].append(dict(chi=chi,th=th,zpos=zpos,rbx=rbx,sigma=sg,span=span,fim=ev,
            yscale=ys,qoff=qoff,nsoft=soft,family=mem,g=g,rep=rep,m=m,kin_family=kin,par_family=par,dz=dz))
        if verbose and ci<4:
            print(f"  cand {ci+1}: Parratt chi2/N={chi:6.1f}  yscale={ys:.2f} qoff={qoff:+.1e}  "
                  f"interior z={np.round(zpos[1:-1],1)} rho={np.round(rbx,2)} sig={sg:.1f}  "
                  f"FIM {soft}soft/{np.log10(ev[0]/ev[-1]):.0f}dec | family {len(mem)}(m={m})")
    return out


def param_table(out):
    """Per candidate: FIM covariance (scaled by reduced chi2) propagated to physical
    parameters. Returns a list of dicts with (value, sigma) for span, interior interface
    positions, box densities, and roughness."""
    N, rt, rb = out['N'], out['rt'], out['rb']; rows = []
    for ci, c in enumerate(out['basin']):
        th = np.asarray(c['th'], float)
        w, V = PL.fim_full(out['q'], out['e'], th, N, rt, rb, kind='kin')
        cov = max(c['chi'], 1.0) * (V @ np.diag(1.0/w) @ V.T)        # external-error inflation
        sd = np.sqrt(np.clip(np.diag(cov), 0, None))
        span, sspan = float(th[0]), float(sd[0])
        interior = []
        for j in range(1, N):                                       # z_j = u_j * span (propagate)
            u = th[j]; g = np.zeros(len(th)); g[j] = span; g[0] = u
            interior.append((float(u*span), float(np.sqrt(max(g @ cov @ g, 0.0)))))
        dens = [(float(th[N+k]), float(sd[N+k])) for k in range(N)]
        sigma = (float(th[2*N]), float(sd[2*N]))
        rows.append(dict(cand=ci+1, chi2_N=float(c['chi']), nsoft=int(c['nsoft']),
                         yscale=float(c['yscale']), qoff=float(c['qoff']),
                         family_size=int(len(c['family'])), span=(span, sspan),
                         interior=interior, densities=dens, sigma=sigma))
    return rows


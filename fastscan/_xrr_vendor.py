def edp_th(zz, th, N, rt, rb):
    zpos, rbx, sg, span = NB._unpack_sb(th, N); dens = [rt] + list(rbx) + [rb]
    st = [dens[k+1]-dens[k] for k in range(len(zpos))]; o = np.full_like(zz, rt)
    for zi, si in zip(zpos, st): o += si*0.5*(1+erf((zz-zi)/(np.sqrt(2)*max(sg, 1.0))))
    return o

def edp_grid(zz, g, dz, sg, rt):
    o = np.full_like(zz, rt)
    for k, s in enumerate(g): o += s*0.5*(1+erf((zz-k*dz)/(np.sqrt(2)*max(sg, 1.0))))
    return o

def _bounds(N, rt, L):
    lb = np.array([PL.SPAN_LO*L]+[0.02]*(N-1)+[rt-0.15]*N+[1.0])
    ub = np.array([PL.SPAN_HI*L]+[0.98]*(N-1)+[PL.RHO_HI]*N+[8.0])
    return lb, ub


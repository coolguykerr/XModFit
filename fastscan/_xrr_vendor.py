def load_rrf(path):
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.replace(',', ' ').split()
            if len(parts) < 3:
                continue
            try:
                rows.append([float(parts[0]), float(parts[1]), float(parts[2])])
            except ValueError:
                continue
    a = np.array(rows)
    q, r, e = a[:, 0], a[:, 1], a[:, 2]
    order = np.argsort(q)
    return q[order], r[order], e[order]

def precondition(q, r, e, dq=None, q0=0.0):
    if dq is None:
        dq = max(np.min(np.diff(q)), 1e-3)
    qmax = q.max()
    qu = np.arange(q0, qmax + 0.5 * dq, dq)
    fr = interp1d(q, r, kind='linear', bounds_error=False, fill_value=np.nan)
    fe = interp1d(q, e, kind='linear', bounds_error=False, fill_value=np.nan)
    ru = fr(qu); eu = fe(qu)
    qmin = q.min()
    below = qu < qmin
    r_at_qmin = r[0]
    frac = qu[below] / max(qmin, 1e-9)
    ru[below] = 1.0 + (r_at_qmin - 1.0) * frac**2
    eu[below] = np.nanmax(e) * 3.0
    good = np.isfinite(ru)
    return qu[good], ru[good], eu[good], dq

def patterson(qu, ru, dq, beta=6.0, pad_factor=8):
    n = len(qu)
    full = windows.kaiser(2 * n, beta)
    taper = full[n:]
    rw = ru * taper
    Npad = pad_factor * 2 ** int(np.ceil(np.log2(max(n, 2))))
    spectrum = np.zeros(Npad // 2 + 1)
    spectrum[:n] = rw
    G_full = irfft(spectrum, n=Npad) * (Npad * dq) / (2 * np.pi)
    dz = 2 * np.pi / (Npad * dq)
    half = Npad // 2
    z = np.arange(half) * dz
    return z, G_full[:half], dz, taper

def patterson_error(qu, eu, dq, taper, nz, dz):
    z = np.arange(nz) * dz
    var = np.zeros(nz)
    wdq = taper * dq
    for iz, zz in enumerate(z):
        c = np.cos(qu * zz)
        var[iz] = np.sum((wdq * c) ** 2 * eu ** 2)
    return np.sqrt(var)

class BoxModel:
    """N-box model: N+1 interfaces. Free params packed as
    [z0, t_1..t_N, Delta_0..Delta_{N-1}, sigma, A] where z0 is the first
    interface position and t_i>0 are successive layer thicknesses, so interface
    positions z_i = z0 + sum(t_1..t_i) are MONOTONIC by construction.
    Delta_N fixed by sum(Delta) = contrast = rho_bottom - rho_top."""
    def __init__(self, N, rho_top, rho_bottom):
        self.N = N                      # boxes
        self.nif = N + 1                # interfaces
        self.rho_top = rho_top
        self.rho_bottom = rho_bottom
        self.contrast = rho_bottom - rho_top

    def unpack(self, p):
        nif = self.nif
        z0 = p[0]
        thick = np.array(p[1:nif])              # N positive thicknesses
        zpos = np.concatenate([[z0], z0 + np.cumsum(thick)])
        steps = np.empty(nif)
        steps[:nif-1] = p[nif:2*nif-1]
        steps[-1] = self.contrast - np.sum(steps[:nif-1])
        sigma = p[2*nif-1]
        A = p[2*nif]
        return zpos, steps, sigma, A

    def npar(self):
        return 2*self.nif + 1           # z0 + thick(N) + steps(nif-1) + sigma + A

    def patterson_G(self, p, z):
        zpos, steps, sigma, A = self.unpack(p)
        w = np.sqrt(2.0) * sigma
        norm = 1.0 / (np.sqrt(2*np.pi) * w)
        # all pairwise lags and amplitudes, vectorized
        lags = (zpos[:, None] - zpos[None, :]).ravel()        # (nif^2,)
        amps = (steps[:, None] * steps[None, :]).ravel()      # (nif^2,)
        # G(z) = A * sum_pairs amp * norm * exp(-(z-lag)^2/(2 w^2))
        zc = z[:, None]                                        # (nz,1)
        E = np.exp(-(zc - lags[None, :])**2 / (2*w**2))       # (nz, nif^2)
        return A * norm * (E @ amps)

    def densities(self, zpos, steps):
        """Absolute layer densities, top side inward (cumulative)."""
        rho = self.rho_top + np.cumsum(steps)
        thick = np.diff(zpos)
        return rho, thick

def turnpike_positions(resolved_lags, span, nif, tol=2.0):
    """
    Deterministic turnpike enumeration: find sets of nif interface positions in
    [0, span] (with 0 and span as the two outer interfaces) whose pairwise
    separations reproduce the RESOLVED Patterson lags. For small nif and few
    resolved lags this is a finite, reproducible backtracking search.

    When the number of resolved interior lags is smaller than needed to pin all
    interior positions (the data-limited case, typical for liquid-liquid), the
    unresolved interior positions are placed on a deterministic grid of splits
    rather than sampled randomly. Returns a list of position arrays (each length
    nif, sorted, endpoints 0 and span).
    """
    n_interior = nif - 2          # interior interfaces between the two outer
    if n_interior <= 0:
        return [np.array([0.0, span])]

    # interior lags that are resolved and lie strictly inside (0, span)
    interior_lags = sorted(set(round(l, 1) for l in resolved_lags
                               if tol < l < span - tol))

    positions = []
    if len(interior_lags) >= n_interior:
        # enough resolved structure: place interior interfaces AT resolved lags,
        # enumerating which resolved lags are interface positions vs. which are
        # difference-lags. Deterministic combinations.
        from itertools import combinations
        for combo in combinations(interior_lags, n_interior):
            pos = np.array([0.0] + list(combo) + [span])
            pos = np.sort(pos)
            if np.all(np.diff(pos) > tol):
                positions.append(pos)
    else:
        # data-limited: interior positions not individually resolved. Enumerate
        # a DETERMINISTIC grid of interior splits (fixed fractions of the span),
        # giving distinct interior arrangements without randomness.
        from itertools import combinations
        # grid must have at least n_interior points; keep modest above that so
        # the deterministic enumeration stays bounded for N up to ~10.
        n_grid = min(n_interior + 3, 10)
        grid = np.linspace(0.10, 0.90, n_grid) * span      # candidate interior pos
        for combo in combinations(grid, n_interior):
            pos = np.array([0.0] + list(combo) + [span])
            pos = np.sort(pos)
            if np.all(np.diff(pos) > tol):
                positions.append(pos)
    if not positions:                                    # fallback: even split
        positions = [np.linspace(0, span, nif)]
    return positions

def sign_partners(nif):
    """
    Deterministic step-sign assignments (the Blaschke / root-flip degeneracy).
    The Patterson fixes products Delta_i*Delta_j, not individual signs. We
    enumerate sign patterns for the nif-1 free steps (the last is fixed by the
    endpoint contrast). For small nif this is 2^(nif-1) patterns; we keep all of
    them and let the fit + endpoint constraint reject the inconsistent ones.
    Returns a list of sign vectors (length nif-1) of +/-1.
    """
    from itertools import product
    return [np.array(s) for s in product([1.0, -1.0], repeat=nif-1)]

def enumerate_topologies(N, span, resolved_lags, contrast):
    """
    Fully DETERMINISTIC enumeration of homometric topologies, = product of
    turnpike position-sets x admissible sign partners. Sign patterns whose
    implied final step (fixed by the endpoint contrast) is inconsistent with
    the pattern are pruned BEFORE fitting -- they are not valid partners. No
    randomness; same input -> same output.

    Returns list of dicts {'zpos': array(nif), 'signs': array(nif-1)}.
    """
    nif = N + 1
    position_sets = turnpike_positions(resolved_lags, span, nif)
    all_signs = sign_partners(nif)
    seeds = []
    for pos in position_sets:
        for sg in all_signs:
            # quick admissibility: with equal-magnitude steps of the contrast
            # scale, can the signed sum plausibly reach the contrast? Prune
            # patterns where all free steps share a sign opposite to contrast
            # (cannot sum toward it). This is a deterministic pre-filter.
            if contrast != 0 and np.all(np.sign(sg) == -np.sign(contrast)):
                continue
            seeds.append({'zpos': pos, 'signs': sg})
    return seeds

def fit_topology(model, z, G, Gerr, seed, sigma0):
    nif = model.nif
    N = model.N
    contrast = model.contrast
    zpos0 = seed['zpos']
    signs = seed['signs']
    span = zpos0[-1] - zpos0[0]
    zmax_fit = span + 3 * sigma0
    m = z <= zmax_fit
    zf, Gf, Wf = z[m], G[m], 1.0 / np.maximum(Gerr[m], 1e-12)
    G0 = G[np.argmin(np.abs(z))]

    def resid(p):
        return (model.patterson_G(p, zf) - Gf) * Wf

    # params: [z0, t_1..t_N, steps(nif-1), sigma, A]
    thick0 = np.diff(zpos0)
    lb = [-5.0] + [1.5]*N + [-0.6]*(nif-1) + [1.0, 1e-4]
    ub = [5.0] + [span*1.1]*N + [0.6]*(nif-1) + [8.0, 1e3]
    lb = np.array(lb); ub = np.array(ub)

    # DETERMINISTIC step seed: equal-magnitude split of the contrast, with the
    # enumerated sign pattern applied to the free steps. A couple of fixed
    # magnitude scales give numerical robustness (not randomness).
    found = []
    for scale in (1.0,):
        mag = scale * abs(contrast) / nif + 0.02
        sp = signs * mag
        p0 = np.concatenate([[zpos0[0]], thick0, sp, [sigma0], [max(G0, 1e-3)]])
        p0 = np.clip(p0, lb, ub)
        try:
            res = least_squares(resid, p0, bounds=(lb, ub),
                                method='trf', max_nfev=2000)
            found.append(res)
        except Exception:
            continue
    return found

def patterson_main(path, N, rho_top, rho_bottom):
    print("=" * 72)
    print(f"PATTERSON N-BOX ANALYSIS  (N={N} boxes, {N+1} interfaces)")
    print(f"endpoints: rho_top={rho_top}, rho_bottom={rho_bottom}, "
          f"contrast={rho_bottom-rho_top:.4f}")
    print("=" * 72)

    q, r, e = load_rrf(path)
    print(f"STEP 0: loaded {len(q)} pts, q in [{q.min():.4f},{q.max():.4f}], "
          f"median rel err {np.median(e/np.abs(r)):.3f}")

    qu, ru, eu, dq = precondition(q, r, e)
    print(f"STEP 1: uniform grid dq={dq:.4f}, {len(qu)} pts; "
          f"resolution 2pi/qmax = {2*np.pi/qu.max():.2f} A")

    z, G, dz, taper = patterson(qu, ru, dq, beta=6.0)
    Gerr = patterson_error(qu, eu, dq, taper, len(z), dz)
    print(f"STEP 2: Patterson computed, dz={dz:.3f} A")

    # peak inventory
    excl = 5.0
    pos = z > excl
    Gabs = np.abs(G)
    pk, _ = find_peaks(Gabs[pos], height=0.05 * Gabs[pos].max())
    zpk = z[pos][pk]; hpk = G[pos][pk]
    print("STEP 2b: off-origin Patterson peaks:")
    for zz, hh in zip(zpk, hpk):
        print(f"    z={zz:6.2f} A   G={hh:+.4e}  ({'+' if hh>0 else '-'})")
    resolution = 2*np.pi/qu.max()
    # The span is the OUTERMOST resolved lag, because G(span) = d_0 d_N is the single
    # end-to-end pair (theory.md S10). Using the LARGEST peak instead is wrong whenever
    # an end contrast is weak -- exactly the ErLD case, where d_0 d_N ~ 2e-4 << G(0) --
    # and it disagreed with resolve_patterson, which already used the outermost peak.
    span = zpk.max() if len(zpk) else 30.0
    if len(zpk):
        h_outer = abs(hpk[np.argmax(zpk)]); h_max = np.max(np.abs(hpk))
        if h_outer < 0.25*h_max:
            print(f"    WARNING: outermost peak (z={span:.1f} A, |G|={h_outer:.2e}) is only "
                  f"{h_outer/h_max:.0%} of the largest peak -- weak end contrast, span may be "
                  f"under-read (theory.md S10 caveat).")
    print(f"    overall span (largest peak) ~ {span:.2f} A; "
          f"interfaces below ~{resolution:.1f} A unresolved")

    model = BoxModel(N, rho_top, rho_bottom)
    resolved_lags = list(zpk)
    seeds = enumerate_topologies(N, span, resolved_lags, model.contrast)
    print(f"STEP 4: deterministically enumerating {len(seeds)} topology seeds "
          f"(turnpike positions x sign partners)")

    raw = []
    for s in seeds:
        for res in fit_topology(model, z, G, Gerr, s, sigma0=3.0):
            zpos, steps, sigma, A = model.unpack(res.x)
            chi2 = np.sum(res.fun**2) / max(len(res.fun) - model.npar(), 1)
            raw.append((chi2, res.x, zpos, steps, sigma))

    # ---- deterministic physical filtering ----
    def physical(zpos, steps, sigma):
        rho, th = model.densities(zpos, steps)
        rho_full = np.concatenate([[rho_top], rho])
        # (a) densities within a physically plausible window for these liquids
        if np.any(rho_full < -0.02) or np.any(rho_full > 0.60):
            return False
        # (b) endpoint must be reached
        if abs(rho[-1] - rho_bottom) > 1e-6:
            return False
        # (c) no layer thinner than ~half the resolution (sub-resolution feature)
        if np.any(th < 0.5 * resolution * 0.5):
            return False
        # (d) total span not wildly beyond the largest resolved lag
        if (zpos[-1] - zpos[0]) > 1.4 * max(resolved_lags + [span]):
            return False
        return True

    # dedupe by ordered steps + thicknesses; keep only physical; rank by chi2
    def thick_t(zp): return tuple(np.round(np.diff(zp), 1))
    def same(a, b):
        return (np.allclose(np.sort(a[3]), np.sort(b[3]), atol=0.02) and
                np.allclose(sorted(thick_t(a[2])), sorted(thick_t(b[2])), atol=1.5))
    fits = []
    n_unphysical = 0
    for cand in sorted(raw, key=lambda t: t[0]):
        if not physical(cand[2], cand[3], cand[4]):
            n_unphysical += 1
            continue
        if not any(same(cand, f) for f in fits):
            fits.append(cand)
    print(f"    ({len(raw)} fits; {n_unphysical} rejected as unphysical; "
          f"{len(fits)} distinct physical members)")

    print("=" * 72)
    print(f"HOMOMETRIC SET ({len(fits)} distinct members, ranked by chi2/dof):")
    for k, (chi2, p, zpos, steps, sigma) in enumerate(fits):
        rho, th = model.densities(zpos, steps)
        print(f"  MEMBER #{k+1}  chi2/dof={chi2:.3f}  sigma={sigma:.2f} A")
        print(f"    interface z (A): {np.round(zpos,2)}")
        print(f"    steps (e/A^3)  : {np.round(steps,4)}")
        print(f"    layer rho      : {np.round(rho,4)}  (target end {rho_bottom})")
        print(f"    thicknesses (A): {np.round(th,2)}")

    np.savez('/home/claude/patterson_Nbox_out.npz',
             qu=qu, ru=ru, eu=eu, taper=taper, z=z, G=G, Gerr=Gerr,
             N=N, rho_top=rho_top, rho_bottom=rho_bottom,
             fits=np.array([f[1] for f in fits], dtype=object) if fits else np.array([]),
             chi2=np.array([f[0] for f in fits]))
    print(f"\n  saved patterson_Nbox_out.npz ({len(fits)} members)")
    return fits



RHO_VAPOR = 0.0

RHO_WATER = 0.333

ENERGY_keV = 10.0

DZ = 0.5

def parratt_py(q, lam, d, rho, beta):
    q = np.asarray(q, float)
    f1 = 16.0*np.pi*2.818e-5
    f2 = -32.0*np.pi**2/lam**2
    Nl = len(d)
    ref = np.ones_like(q)
    for j in range(len(q)):
        r = complex(0.0, 0.0)
        for it in range(1, Nl):
            i = Nl - it
            qc1 = f1*(rho[i-1]-rho[0])
            qc2 = f1*(rho[i]-rho[0])
            k1 = np.sqrt(complex(q[j]**2-qc1, f2*beta[i-1]))
            k2 = np.sqrt(complex(q[j]**2-qc2, f2*beta[i]))
            X = (k1-k2)/(k1+k2)
            fact1 = complex(math.cos(k2.real*d[i]), math.sin(k2.real*d[i]))
            fact2 = math.exp(-k2.imag*d[i])
            fact = fact1*fact2
            r = (X+r*fact)/(1.0+X*r*fact)
        ref[j] = abs(r)**2
    return ref

def sldCalFun(d, y, sigma, x):
    wholesld = []
    for j in range(len(x)):
        sld = 0
        for i in range(len(d)-1):
            pos = np.sum(d[:i+1])
            sld = sld + math.erf((x[j]-pos)/sigma[i+1]/math.sqrt(2))*(y[i+1]-y[i])
        wholesld.append(max((sld+y[0]+y[-1])/2, 0))
    return wholesld

def calcProfile(d, rho, mu, sig, dz):
    d = np.array(d); rho = np.array(rho); mu = np.array(mu); sig = np.array(sig)
    maxsig = max(np.abs(np.max(sig[1:])), 3)
    Nlayers = int((np.sum(d[:-1])+10*maxsig)/dz)
    halfstep = (np.sum(d[:-1])+10*maxsig)/2/Nlayers
    z = np.linspace(-5*maxsig+halfstep, np.sum(d[:-1])+5*maxsig-halfstep, Nlayers)
    dd = np.diff(z); dd = np.append(dd, [dd[-1]])
    rr = sldCalFun(tuple(d), tuple(rho), tuple(sig), tuple(z))
    mm = sldCalFun(tuple(d), tuple(mu), tuple(sig), tuple(z))
    return z, dd, np.array(rr), np.array(mm)

def lam_from_E(E):
    return 6.62607004e-34*2.99792458e8*1e10/E/1e3/1.60217662e-19

def RoRF_model(q, d1, d2, r1, r2, sigma):
    lam = lam_from_E(ENERGY_keV)
    # XLayers layer arrays: [top, L1, L2, bottom]; top d ignored, bottom d=1
    d = [0.0, d1, d2, 1.0]
    rho = [RHO_VAPOR, r1, r2, RHO_WATER]
    mu = [0.0, 0.0, 0.0, 0.0]
    sig = [0.0, sigma, sigma, sigma]      # top roughness 0; fix_sig ties the rest
    z, dd, rr, mm = calcProfile(d, rho, mu, sig, DZ)
    refq = parratt_py(q, lam, tuple(dd), tuple(rr), tuple(mm))
    ref = parratt_py(q, lam, (0.0, 1.0), (RHO_VAPOR, RHO_WATER), (0.0, 0.0))
    return refq/ref

def fit_one(q, data, err, p0):
    lb = [3, 3, -0.10, -0.10, 1.0]
    ub = [35, 35, 0.65, 0.65, 7.0]
    def resid(p):
        return (RoRF_model(q, *p)-data)/np.maximum(err, 1e-6)
    p0 = list(np.clip(p0, lb, ub))
    res = least_squares(resid, p0, bounds=(lb, ub), method='trf',
                        x_scale=[10, 10, 0.1, 0.1, 1.0], max_nfev=4000)
    chi2 = np.sum(res.fun**2)/max(len(q)-5, 1)
    chi2_start = np.sum(resid(p0)**2)/max(len(q)-5, 1)
    return res, chi2, chi2_start



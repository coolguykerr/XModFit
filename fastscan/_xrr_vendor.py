def estimate_order(q, r, sigma_guess=3.0, nuni=140, kmax=15):
    """Matrix-pencil / Hankel-SVD order estimate. |F(q)|^2 is a sum of cosines in q (one per
    interface-pair separation), so the singular-value spectrum of a Hankel matrix of the
    roughness-deconvolved data reveals the model order, super-resolved below the Fourier limit.
    Hankel rank R = 2*(#separations)+1; #interfaces follows from the separation count.
    Returns (normalized singular values, R, n_separations, N_estimate)."""
    qa, idx = np.unique(np.asarray(q, float), return_index=True)   # sorted, de-duplicated q
    ra = np.asarray(r, float)[idx]
    qu = np.linspace(qa.min(), qa.max(), nuni)
    ru = interp1d(qa, ra, kind='cubic')(qu)
    ysharp = ru/np.exp(-(sigma_guess*qu)**2)                 # deconvolve the roughness envelope
    Nn = len(ysharp); L = Nn//2
    Y = np.array([ysharp[i:i+L+1] for i in range(Nn-L)])     # Hankel matrix
    s = np.linalg.svd(Y, compute_uv=False); sn = s/s[0]
    K = min(kmax, len(sn)-1)
    drops = sn[:K]/(sn[1:K+1]+1e-12)                         # largest gap = signal/noise edge
    R = int(np.argmax(drops))+1
    n_sep = max(1, (R-1)//2)                                 # R = 2*#sep + 1 (DC term)
    n_iface = (1+np.sqrt(1+8*n_sep))/2                       # k interfaces -> up to k(k-1)/2 seps
    N_est = max(1, int(round(n_iface))-1)
    return sn, R, n_sep, N_est

def model_selection(summary, n_data, n_nuisance):
    """Augment the per-N summary with BIC and a nested F-test between consecutive box counts.
    chi (=chi2/N here) is the mean squared standardized residual, so total chi2 = chi*n_data."""
    rows = sorted(summary, key=lambda s: s['N'])
    for s in rows:
        k = s['total_params'] + n_nuisance
        chi2 = s['best_chi2_N']*n_data
        s['k'] = k; s['chi2_total'] = chi2
        s['BIC'] = chi2 + k*np.log(n_data)
    for i, s in enumerate(rows):
        if i == 0: s['dBIC']=None; s['Ftest_p']=None; continue
        p = rows[i-1]
        dk = s['k']-p['k']
        if dk > 0 and (n_data-s['k']) > 0 and s['chi2_total'] < p['chi2_total']:
            F = ((p['chi2_total']-s['chi2_total'])/dk)/(s['chi2_total']/(n_data-s['k']))
            s['Ftest_p'] = float(_fdist.sf(F, dk, n_data-s['k']))
        else:
            s['Ftest_p'] = 1.0
        s['dBIC'] = s['BIC']-p['BIC']
    best = min(rows, key=lambda s: s['BIC'])
    return rows, best

def analyze(path, rt, rb, Ns, outdir, name, fit_yscale=True, fit_qoff=True,
            family_samples=40, quick=False, sigma_guess=3.0):
    os.makedirs(outdir, exist_ok=True)
    # data-driven order hint (independent of N)
    q0, r0, e0 = PN.load_rrf(path); n_data = len(q0)
    sn, R, n_sep, N_est = estimate_order(q0, r0, sigma_guess=sigma_guess)
    print('\nData-driven order estimate (matrix-pencil / Hankel-SVD):')
    print('  singular values (normalized): ' + ' '.join('%.3f' % v for v in sn[:8]))
    print('  Hankel rank R=%d -> ~%d interface-pair separation(s) -> N ~ %d boxes' % (R, n_sep, N_est))
    print('  (a data-driven *starting* guess; confirm by fitting a range and the criteria below)')

    summary = []
    n_nuis = (1 if fit_yscale else 0) + (1 if fit_qoff else 0)
    for N in Ns:
        sub = os.path.join(outdir, 'N%d' % N); os.makedirs(sub, exist_ok=True)
        print('\n' + '='*70 + '\n  N = %d boxes\n' % N + '='*70)
        out = PL.run_pipeline(path, rb-rt, rt, rb, N, name='%s (N=%d)' % (name, N),
                              verbose=True, fit_yscale=fit_yscale, fit_qoff=fit_qoff)
        if not out['basin']:
            print('  no admissible candidates for N=%d' % N); continue
        write_tables(out, sub)
        plot_patterson(out, sub); plot_basin(out, sub); plot_fim(out, sub)
        plot_homometric(out, sub); plot_qmax(out, sub)
        if not quick: plot_family_basin(out, sub, M=family_samples)
        best = min(out['basin'], key=lambda c: c['chi'])
        summary.append(dict(N=N, n_candidates=len(out['basin']), best_chi2_N=best['chi'],
                            nsoft=best['nsoft'], total_params=2*N+1, yscale=best['yscale']))
        print('  wrote %d figures + candidates.csv / parameters.csv / candidates.json to %s'
              % (5 if quick else 6, sub))

    # cross-N model comparison with BIC + F-test
    if summary:
        rows, best = model_selection(summary, n_data, n_nuis)
        with open(os.path.join(outdir, 'model_comparison.csv'), 'w', newline='') as f:
            wr = csv.writer(f)
            wr.writerow(['N_boxes', 'n_candidates', 'best_chi2_N', 'nsoft', 'k_params',
                         'chi2_total', 'BIC', 'dBIC_vs_prev', 'Ftest_p_vs_prev', 'yscale'])
            for s in rows:
                wr.writerow([s['N'], s['n_candidates'], '%.3f' % s['best_chi2_N'], s['nsoft'], s['k'],
                             '%.1f' % s['chi2_total'], '%.1f' % s['BIC'],
                             '' if s['dBIC'] is None else '%.1f' % s['dBIC'],
                             '' if s['Ftest_p'] is None else '%.3g' % s['Ftest_p'], '%.3f' % s['yscale']])
        print('\n' + '-'*70)
        print('Model selection across N:')
        print('  %-3s %10s %6s %8s %12s %10s' % ('N', 'chi2/N', 'nsoft', 'BIC', 'dBIC(prev)', 'F-test p'))
        for s in rows:
            print('  %-3d %10.1f %6d %8.0f %12s %10s' % (
                s['N'], s['best_chi2_N'], s['nsoft'], s['BIC'],
                '-' if s['dBIC'] is None else '%.0f' % s['dBIC'],
                '-' if s['Ftest_p'] is None else '%.3g' % s['Ftest_p']))
        print('  data-driven order hint: N ~ %d ;  minimum-BIC model: N = %d' % (N_est, best['N']))
        print('  caveat: chi2/N >> 1 makes absolute BIC/F-test p-values unreliable; read them')
        print('  comparatively, and prefer the smallest N where chi2/N stops dropping and the')
        print('  soft-direction count (nsoft) starts to climb (over-boxing shows up as soft dirs).')
    print('\nFull results under: %s' % os.path.abspath(outdir))
    return summary

def _parse_Ns(s):
    out = []
    for part in str(s).split(','):
        if '-' in part: a, b = part.split('-'); out += list(range(int(a), int(b)+1))
        else: out.append(int(part))
    return sorted(set(out))

